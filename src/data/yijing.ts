export function getYijingQuotes(): YijingQuote[] {
  return YIJING_QUOTES;
}

export function getYijingQuoteBySource(source: string): YijingQuote[] {
  return YIJING_QUOTES.filter(q => q.source.includes(source));
}

export function getRandomYijingQuote(): YijingQuote {
  return YIJING_QUOTES[Math.floor(Math.random() * YIJING_QUOTES.length)];
}

/** 获取每日一句易经 */
export function getDailyYijingQuote(): YijingQuote {
  const today = new Date();
  const index = (today.getFullYear() * 365 + today.getMonth() * 30 + today.getDate()) % YIJING_QUOTES.length;
  return YIJING_QUOTES[index];
}
